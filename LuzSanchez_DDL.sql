--6. CREAR UNA VISTA DE DOCUMENTOS PENDIENTES
CREATE VIEW VISTA_DOCUMENTOS_PENDIENTES AS
SELECT ID_DOCUMENTO, TIPO_REMITENTE, FECHA_RECEPCION, ESTADO
FROM DOCUMENTO
WHERE ESTADO = 'PENDIENTE'
GO

SELECT *
FROM VISTA_DOCUMENTOS_PENDIENTES 
GO

--7. CREAR UNA VISTA PARA CONSULTAR LOS ESTUDIANTES MAYORES DE 15 AÑOS
CREATE VIEW VISTA_ESTUDIANTES_MAYORES AS
SELECT ID_ESTUDIANTE, NOMBRE, APELLIDO_PATERNO, APELLIDO_MATERNO, EDAD
FROM ESTUDIANTE
WHERE EDAD > 15
GO

SELECT * FROM VISTA_ESTUDIANTES_MAYORES
GO

--8. AGREGAR UN ATRIBUTO PARA REGISTRAR LA OBSERVACION DEL AULA
ALTER TABLE AULA
ADD OBSERVACION VARCHAR(100) NULL

--9. CREAR UNA VISTA PARA CONSULTAR LOS ESTUDIANTES CON SU INSTITUCION DE PROCEDENCIA
CREATE VIEW VISTA_ESTUDIANTES_PROCEDENCIA AS
SELECT E.ID_ESTUDIANTE, E.NOMBRE, E.APELLIDO_PATERNO, I.RAZON_SOCIAL
FROM ESTUDIANTE E
INNER JOIN INSTITUCION_PROCEDENCIA I
ON E.CM_IE = I.CODIGO_MODULAR
GO

SELECT * FROM VISTA_ESTUDIANTES_PROCEDENCIA
GO

--10. AGREGAR UNA RESTRICCION PARA VALIDAR LAS FECHAS DE LOS DOCUMENTOS
ALTER TABLE DOCUMENTO
ADD CONSTRAINT CK_DOCUMENTO_FECHAS
CHECK (FECHA_RESOLUCION IS NULL OR FECHA_RESOLUCION >= FECHA_RECEPCION)


--11. CREAR UNA VISTA PARA CONSULTAR LAS SECCIONES Y SUS AULAS
CREATE VIEW VISTA_SECCIONES_AULAS AS
SELECT S.ID_SECCION, S.GRADO, S.SECCION, S.ANIO_VIGENTE, A.ID_AULA, A.PISO, A.TIPO
FROM SECCION S
INNER JOIN AULA A
ON S.IDAULA = A.ID_AULA
GO

SELECT * FROM VISTA_SECCIONES_AULAS
GO

